// Run: node --test load/k6/*.test.mjs
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { arrivalRate, journalEntry, soakFraction, thresholds, uuid } from './lib.js';

const SLO = JSON.parse(readFileSync(new URL('../slo/slo.json', import.meta.url)));
const POOL = JSON.parse(readFileSync(new URL('./data/pool.example.json', import.meta.url)));

test('every SLO row produces a k6 threshold', () => {
  const t = thresholds(SLO, 1);
  for (const s of SLO.slos) {
    const key = s.op ? `http_req_duration{op:${s.op}}` : s.metric;
    if (s.op && s.p95ms === undefined && s.p99ms === undefined) continue;
    assert.ok(t[key], `no threshold for ${s.id}`);
  }
  assert.deepEqual(t['http_req_duration{op:entity_read}'], ['p(95)<50', 'p(99)<150']);
  assert.deepEqual(t['http_req_failed{op:journal_post}'], ['rate<0.0005']);
  assert.deepEqual(t['mrp_run_seconds'], ['max<600']);
  assert.deepEqual(t['mrp_runs_completed'], ['count>=1']);
});

test('throughput thresholds are per second and follow LOAD_SCALE', () => {
  assert.deepEqual(thresholds(SLO, 1)['journal_lines_posted'], ['rate>=277.7778']);
  assert.deepEqual(thresholds(SLO, 0.1)['order_lines_accepted'], ['rate>=2.7778']);
  // Latency limits do not scale.
  assert.deepEqual(thresholds(SLO, 0.1)['http_req_duration{op:pricing}'], ['p(95)<20']);
});

test('journal entry is balanced, uses decimal strings and the pool accounts', () => {
  const e = journalEntry(POOL, 500, 'c1');
  assert.equal(e.lines.length, 500);
  assert.equal(e.ledgerId, POOL.ledgerId);
  assert.match(e.documentId, /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/);
  assert.match(e.source.id, /^c1-/);
  const cents = { D: 0n, C: 0n };
  for (const l of e.lines) {
    assert.equal(typeof l.amount.value, 'string');
    assert.match(l.amount.value, /^\d+\.\d{2}$/);
    assert.ok(POOL.accounts.includes(l.account));
    cents[l.debitCredit] += BigInt(l.amount.value.replace('.', ''));
  }
  assert.equal(cents.D, cents.C);
  const debitAccounts = new Set(e.lines.filter((l) => l.debitCredit === 'D').map((l) => l.account));
  const creditAccounts = new Set(e.lines.filter((l) => l.debitCredit === 'C').map((l) => l.account));
  for (const a of debitAccounts) assert.ok(!creditAccounts.has(a), `account ${a} on both sides`);
});

test('journal entry rejects an odd line count and a pool without two accounts', () => {
  assert.throws(() => journalEntry(POOL, 3, 'c1'), /even/);
  assert.throws(() => journalEntry({ ...POOL, accounts: ['6100'] }, 2, 'c1'), /debit and one credit/);
});

test('uuid is v4 shaped and unique', () => {
  const seen = new Set();
  for (let i = 0; i < 1000; i++) seen.add(uuid());
  assert.equal(seen.size, 1000);
});

test('soak thresholds cover only the soak SLO rows, at the soak fraction', () => {
  const t = thresholds(SLO, soakFraction(SLO, 1), SLO.soak.slos);
  assert.deepEqual(Object.keys(t).sort(), [
    'http_req_duration{op:dashboard}',
    'http_req_duration{op:entity_read}',
    'http_req_duration{op:form_save}',
    'http_req_duration{op:journal_post}',
    'http_req_failed{op:dashboard}',
    'http_req_failed{op:entity_read}',
    'http_req_failed{op:form_save}',
    'http_req_failed{op:journal_post}',
    'journal_lines_posted',
  ]);
  // 1M lines/h at 50% = 500k/h = 138.8889/s; latency limits are the campaign's.
  assert.deepEqual(t['journal_lines_posted'], ['rate>=138.8889']);
  assert.deepEqual(t['http_req_duration{op:journal_post}'], ['p(99)<2000']);
});

// The scaled arrival rate must never fall below the scaled throughput target the
// checker applies, or a perfect backend fails a smoke run. Expected values are
// hand-derived: S1 34 entries/min x 500 lines x 60 = 1.02M lines/h against 1M;
// S2 170 orders/min x 10 lines x 60 = 102k lines/h against 100k.
test('scaled arrival rates stay at or above the scaled throughput targets', () => {
  // LOAD_SCALE 0.1: S1 34 x 0.1 = 3.4/min. Rounding down to 3 gives 90k lines/h
  // against the 100k target; the rate must be 4 (120k lines/h).
  assert.equal(arrivalRate(34, 0.1), 4);
  // Soak at LOAD_SCALE 0.2 (fraction 0.1): same 3.4/min.
  assert.equal(arrivalRate(34, soakFraction(SLO, 0.2)), 4);
  // LOAD_SCALE 0.3: 10.2/min -> 11 (330k lines/h against 300k), not 10 (exactly 300k, no headroom).
  assert.equal(arrivalRate(34, 0.3), 11);
  // Exact products stay exact: full load and the 50% soak.
  assert.equal(arrivalRate(34, 1), 34);
  assert.equal(arrivalRate(170, 1), 170);
  assert.equal(arrivalRate(34, 0.5), 17);
  assert.equal(arrivalRate(170, 0.1), 17);
  // Never zero.
  assert.equal(arrivalRate(34, 0.001), 1);

  // Property over every scale from 0.001 to 1 in steps of 0.001: lines per hour
  // generated by the scenario >= the target the checker applies at that scale.
  const targets = Object.fromEntries(SLO.slos.filter((s) => s.minPerHour).map((s) => [s.id, s.minPerHour]));
  const shapes = [
    ['journal_throughput', 34, 500],
    ['order_throughput', 170, 10],
  ];
  for (let k = 1; k <= 1000; k++) {
    const scale = k / 1000;
    for (const [id, perMinute, linesPerIteration] of shapes) {
      const linesPerHour = arrivalRate(perMinute, scale) * linesPerIteration * 60;
      assert.ok(linesPerHour >= targets[id] * scale, `${id} at scale ${scale}: ${linesPerHour} lines/h < ${targets[id] * scale}`);
    }
  }
});

test('soak profile and SLO filter reject bad input', () => {
  assert.equal(soakFraction(SLO, 0.1), 0.05);
  assert.throws(() => soakFraction(SLO, 0), /positive/);
  assert.throws(() => soakFraction({ slos: [] }, 1), /no soak profile/);
  assert.throws(() => thresholds(SLO, 1, ['journal_post', 'no_such_row']), /unknown SLO id no_such_row/);
});
