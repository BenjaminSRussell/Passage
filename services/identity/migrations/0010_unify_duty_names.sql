-- #210: duty names are dotted lower-case (policies/authz/README.md). A role assignment names a duty,
-- so every assignment that names a renamed duty moves to the new name, ended and future ones
-- included, so no assignment names a duty the catalogue no longer has. Audit and outbox rows are
-- history and keep the name they were written with. The rename is one-to-one and no new name
-- existed before, so the no-overlap exclusion constraint cannot fire.
--
-- The migrator is the table owner and the table forces row-level security, so the owner would see
-- no rows without a tenant context. FORCE is lifted for this transaction only and restored before
-- it commits; passage_app is never affected.
