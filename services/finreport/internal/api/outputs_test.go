// HTML and XLSX are served from the same stored run as CSV, with their own
// content type and file name, and carry the run's header and footer.
func TestRunOutput_HTMLAndXLSX(t *testing.T) {
	cases := []struct {
		format, contentType string
		check               func(t *testing.T, body []byte)
	}{
		{"html", "text/html; charset=utf-8", func(t *testing.T, body []byte) {
			s := string(body)
			for _, want := range []string{
				"<dt>period</dt><dd>2026-03</dd>",
				`<td class="num">12.500000</td><td class="num">n/a</td>`,
				"<dt>as of sequence</dt><dd>" + ledgerUUID + ": 42</dd>",
				"<dt>generated by</dt><dd>u7</dd>",
				"<dt>run</dt><dd>" + runUUID + "</dd>",
			} {
				if !strings.Contains(s, want) {
					t.Errorf("html missing %q:\n%s", want, s)
				}
			}
		}},
		{"xlsx", "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet", func(t *testing.T, body []byte) {
			zr, err := zip.NewReader(bytes.NewReader(body), int64(len(body)))
			if err != nil {
				t.Fatalf("not a zip archive: %v", err)
			}
			for _, f := range zr.File {
				if f.Name == "xl/worksheets/sheet1.xml" {
					return
				}
			}
			t.Error("workbook has no sheet1.xml")
		}},
	}
	for _, tc := range cases {
		t.Run(tc.format, func(t *testing.T) {
			w := call(scheduleRouter(outputStore{}), http.MethodGet, "/v1/reporting/runs/"+runUUID+"/outputs/"+tc.format, "", nil, DutyView)
			if w.Code != http.StatusOK {
				t.Fatalf("status %d: %s", w.Code, w.Body.String())
			}
			if ct := w.Header().Get("Content-Type"); ct != tc.contentType {
				t.Errorf("Content-Type = %q, want %q", ct, tc.contentType)
			}
			if cd := w.Header().Get("Content-Disposition"); cd != `attachment; filename="TB-STD-`+runUUID+`.`+tc.format+`"` {
				t.Errorf("Content-Disposition = %q", cd)
			}
			tc.check(t, w.Body.Bytes())
		})
	}
}

// The header of a consolidated run's output names every ledger with its label,
// not only the first.
func TestRunOutput_ConsolidatedHeaderNamesEveryLedger(t *testing.T) {
	second := "7b0b1a3e-6f0f-4b52-9d38-2f1c5a0c9a02"
	w := call(scheduleRouter(outputStore{consolidation: []domain.LedgerColumn{{LedgerID: ledgerUUID, Label: "Plant A"}, {LedgerID: second, Label: "Plant B"}}}),
		http.MethodGet, "/v1/reporting/runs/"+runUUID+"/outputs/csv", "", nil, DutyView)
	if w.Code != http.StatusOK {
		t.Fatalf("status %d: %s", w.Code, w.Body.String())
	}
	want := `ledger,"` + ledgerUUID + " (Plant A), " + second + ` (Plant B)"`
	if !strings.Contains(w.Body.String(), want) {
		t.Errorf("csv header lacks %q:\n%s", want, w.Body.String())
	}
}

// A failing renderer answers REPORT-0016 naming the format and the run.
func TestRunOutput_RenderFailure(t *testing.T) {
	saved := outputs.Formats["html"]
	defer func() { outputs.Formats["html"] = saved }()
	outputs.Formats["html"] = outputs.Format{ContentType: saved.ContentType, Render: func(domain.Definition, []domain.Cell, domain.Stamp) ([]byte, error) {
		return nil, errors.New("template broke")
	}}
	w := call(scheduleRouter(outputStore{}), http.MethodGet, "/v1/reporting/runs/"+runUUID+"/outputs/html", "", nil, DutyView)
	if w.Code != http.StatusInternalServerError || problemCode(t, w) != CodeRenderFailed {
		t.Fatalf("status %d: %s", w.Code, w.Body.String())
	}
	if !strings.Contains(w.Body.String(), "html rendering failed for run "+runUUID) {
		t.Errorf("detail does not name the format and run: %s", w.Body.String())
	}
	if strings.Contains(w.Body.String(), "template broke") {
		t.Errorf("internal error text leaked: %s", w.Body.String())
	}
}
