package domain

import (
	"bytes"
	"encoding/csv"
	"fmt"
	"sort"
	"strconv"
	"strings"
	"time"
)

// Stamp is the header and "as of" information every export carries (PRD
// §2.15.6 and §2.15.15): the run and its parameters, the definition version it
// used, the high-water marks it read and the result hash that makes the figures
// reproducible (BR-15.6).
type Stamp struct {
	RunID             string
	DefinitionCode    string
	DefinitionVersion int
	LedgerID          string
	Period            string
	CurrencyType      string
	HWM               map[string]int64
	ResultHash        string
	GeneratedAt       time.Time
	GeneratedBy       string
}

// layout is the content of one statement file, shared by every renderer so
// that the CSV, HTML and XLSX files of a run say exactly the same thing (PRD
// §2.15.15): the header block (statement, definition version, ledger, period,
// currency type), the grid, and the "as of" footer (posting sequence per
// ledger, result hash, generated at and by, run id).
type layout struct {
	title   string
	header  [][2]string
	columns []string
	rows    []layoutRow
	footer  [][]string
}

type layoutRow struct {
	code   string
	label  string
	indent int
	strong bool
	values []layoutValue
}

// layoutValue is one grid cell. An empty text is a blank cell; numeric values
// carry the exact decimal with six places (cells are never rounded, BR-15.6).
type layoutValue struct {
	text    string
	numeric bool
}

func buildLayout(def Definition, cells []Cell, st Stamp) layout {
	idx := make(map[[2]string]Cell, len(cells))
	for _, c := range cells {
		idx[[2]string{c.Row, c.Column}] = c
	}
	lay := layout{
		title: def.Name,
		header: [][2]string{
			{"statement", def.Name},
			{"definition", fmt.Sprintf("%s v%d", st.DefinitionCode, st.DefinitionVersion)},
			{"ledger", st.LedgerID},
			{"period", st.Period},
			{"currency type", st.CurrencyType},
		},
	}
	for _, col := range def.Columns {
		lay.columns = append(lay.columns, col.Label)
	}
	for _, r := range def.Rows {
		row := layoutRow{
			code:   r.Code,
			label:  r.Label,
			indent: min(max(r.Format.Indent, 0), MaxIndent), // versions stored before the bound was checked
			strong: r.Format.Bold || r.Kind == RowHeader || r.Kind == RowTotal,
		}
		for _, col := range def.Columns {
			c, ok := idx[[2]string{r.Code, col.Code}]
			switch {
			case !ok || r.Kind == RowHeader:
				row.values = append(row.values, layoutValue{})
			case c.Blank && c.Note == CodePYMissing: // BR-15.9
				row.values = append(row.values, layoutValue{text: "n/a"})
			case c.Blank:
				row.values = append(row.values, layoutValue{})
			default:
				row.values = append(row.values, layoutValue{text: c.Value.StringFixed(6), numeric: true})
			}
		}
		lay.rows = append(lay.rows, row)
	}
	ledgers := make([]string, 0, len(st.HWM))
	for l := range st.HWM {
		ledgers = append(ledgers, l)
	}
	sort.Strings(ledgers)
	for _, l := range ledgers {
		lay.footer = append(lay.footer, []string{"as of sequence", l, strconv.FormatInt(st.HWM[l], 10)})
	}
	lay.footer = append(lay.footer,
		[]string{"result hash", st.ResultHash},
		[]string{"generated at", st.GeneratedAt.UTC().Format(time.RFC3339)},
		[]string{"generated by", st.GeneratedBy},
		[]string{"run", st.RunID},
	)
	return lay
}

// RenderCSV writes a statement as CSV (FR-15.6): a header block with the
// statement parameters, a blank line, the grid (one line per definition row,
// the label indented by Format.Indent, one column per definition column, exact
// cell values, blank cells empty, "n/a" for a missing prior-year period per
// BR-15.9), a blank line and the "as of" footer. Text that a spreadsheet would
// read as a formula is prefixed with an apostrophe. Equal inputs give equal
// bytes.
func RenderCSV(def Definition, cells []Cell, st Stamp) ([]byte, error) {
	lay := buildLayout(def, cells, st)
	var records [][]string
	for _, h := range lay.header {
		records = append(records, []string{h[0], safeText(h[1])})
	}
	records = append(records, nil)
	header := []string{"row", "label"}
	for _, label := range lay.columns {
		header = append(header, safeText(label))
	}
	records = append(records, header)
	for _, r := range lay.rows {
		line := []string{r.code, safeText(strings.Repeat("  ", r.indent) + r.label)}
		for _, v := range r.values {
			line = append(line, v.text)
		}
		records = append(records, line)
	}
	records = append(records, nil)
	for _, f := range lay.footer {
		rec := append([]string(nil), f...)
		if rec[0] == "generated by" { // the only user text in the footer
			rec[1] = safeText(rec[1])
		}
		records = append(records, rec)
	}
	var buf bytes.Buffer
	w := csv.NewWriter(&buf)
	for _, rec := range records {
		if rec == nil {
			rec = []string{}
		}
		if err := w.Write(rec); err != nil {
			return nil, err
		}
	}
	w.Flush()
	if err := w.Error(); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// safeText neutralizes CSV formula injection: user text starting with = + - @
// or a control character would be evaluated by a spreadsheet.
func safeText(s string) string {
	t := strings.TrimLeft(s, " ")
	if t != "" && strings.ContainsRune("=+-@\t\r", rune(t[0])) {
		return "'" + s
	}
	return s
}
