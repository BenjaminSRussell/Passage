package domain

import (
	"bytes"
	"encoding/csv"
	"fmt"
	"sort"
	"strconv"
	"strings"
	"time"
)

// Stamp is the header and "as of" information every export carries (PRD
// §2.15.6 and §2.15.15): the run and its parameters, the definition version it
// used, the high-water marks it read and the result hash that makes the figures
// reproducible (BR-15.6).
type Stamp struct {
	RunID             string
	DefinitionCode    string
	DefinitionVersion int
	LedgerID          string
	Period            string
	CurrencyType      string
	HWM               map[string]int64
	ResultHash        string
	GeneratedAt       time.Time
	GeneratedBy       string
}

// RenderCSV writes a statement as CSV (FR-15.6): a header block with the
// statement parameters, a blank line, the grid (one line per definition row,
// the label indented by Format.Indent, one column per definition column, exact
// cell values, blank cells empty, "n/a" for a missing prior-year period per
// BR-15.9), a blank line and the "as of" footer. Text that a spreadsheet would
// read as a formula is prefixed with an apostrophe. Equal inputs give equal
// bytes.
func RenderCSV(def Definition, cells []Cell, st Stamp) ([]byte, error) {
	idx := make(map[[2]string]Cell, len(cells))
	for _, c := range cells {
		idx[[2]string{c.Row, c.Column}] = c
	}
	var records [][]string
	records = append(records,
		[]string{"statement", safeText(def.Name)},
		[]string{"definition", fmt.Sprintf("%s v%d", st.DefinitionCode, st.DefinitionVersion)},
		[]string{"ledger", st.LedgerID},
		[]string{"period", st.Period},
		[]string{"currency type", st.CurrencyType},
		nil,
	)
	header := []string{"row", "label"}
	for _, col := range def.Columns {
		header = append(header, safeText(col.Label))
	}
	records = append(records, header)
	for _, r := range def.Rows {
		indent := min(max(r.Format.Indent, 0), MaxIndent) // versions stored before the bound was checked
		line := []string{r.Code, safeText(strings.Repeat("  ", indent) + r.Label)}
		for _, col := range def.Columns {
			c, ok := idx[[2]string{r.Code, col.Code}]
			switch {
			case !ok || r.Kind == RowHeader:
				line = append(line, "")
			case c.Blank && c.Note == CodePYMissing:
				line = append(line, "n/a")
			case c.Blank:
				line = append(line, "")
			default:
				line = append(line, c.Value.StringFixed(6))
			}
		}
		records = append(records, line)
	}
	records = append(records, nil)
	ledgers := make([]string, 0, len(st.HWM))
	for l := range st.HWM {
		ledgers = append(ledgers, l)
	}
	sort.Strings(ledgers)
	for _, l := range ledgers {
		records = append(records, []string{"as of sequence", l, strconv.FormatInt(st.HWM[l], 10)})
	}
	records = append(records,
		[]string{"result hash", st.ResultHash},
		[]string{"generated at", st.GeneratedAt.UTC().Format(time.RFC3339)},
		[]string{"generated by", safeText(st.GeneratedBy)},
		[]string{"run", st.RunID},
	)
	var buf bytes.Buffer
	w := csv.NewWriter(&buf)
	for _, rec := range records {
		if rec == nil {
			rec = []string{}
		}
		if err := w.Write(rec); err != nil {
			return nil, err
		}
	}
	w.Flush()
	if err := w.Error(); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// safeText neutralizes CSV formula injection: user text starting with = + - @
// or a control character would be evaluated by a spreadsheet.
func safeText(s string) string {
	t := strings.TrimLeft(s, " ")
	if t != "" && strings.ContainsRune("=+-@\t\r", rune(t[0])) {
		return "'" + s
	}
	return s
}
