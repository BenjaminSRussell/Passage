package domain

import (
	"strings"
	"testing"
	"time"

	"github.com/shopspring/decimal"
)

func renderFixture() (Definition, []Cell, Stamp) {
	def := Definition{
		Code: "TB-STD", Name: "Trial balance", Kind: KindTrialBalance,
		Rows: []Row{
			{Code: "HDR", Kind: RowHeader, Label: "Assets", NormalBalance: "debit"},
			{Code: "CASH", Kind: RowAccountRange, Label: "Cash", NormalBalance: "debit", Format: Format{Indent: 1}},
			{Code: "EQ", Kind: RowAccountRange, Label: "Equity", NormalBalance: "credit"},
		},
		Columns: []Column{
			{Code: "CUR", Label: "Closing", PeriodExpr: "P", CurrencyType: "acct"},
			{Code: "PY", Label: "Prior year", PeriodExpr: "PY", CurrencyType: "acct"},
		},
	}
	cells := []Cell{
		{Row: "HDR", Column: "CUR", Blank: true},
		{Row: "HDR", Column: "PY", Blank: true},
		{Row: "CASH", Column: "CUR", Value: decimal.RequireFromString("1250.5")},
		{Row: "CASH", Column: "PY", Blank: true, Note: CodePYMissing},
		{Row: "EQ", Column: "CUR", Value: decimal.RequireFromString("-300")},
		{Row: "EQ", Column: "PY", Value: decimal.Zero},
	}
	st := Stamp{
		RunID: "run-1", DefinitionCode: "TB-STD", DefinitionVersion: 2, LedgerID: "ledger-a", Period: "2026-03", CurrencyType: "acct",
		HWM:        map[string]int64{"ledger-b": 9, "ledger-a": 7},
		ResultHash: "abc123", GeneratedAt: time.Date(2026, 4, 1, 8, 0, 0, 0, time.FixedZone("CEST", 2*3600)), GeneratedBy: "u1",
	}
	return def, cells, st
}

func TestRenderCSV_LayoutAndFooter(t *testing.T) {
	def, cells, st := renderFixture()
	out, err := RenderCSV(def, cells, st)
	if err != nil {
		t.Fatal(err)
	}
	lines := strings.Split(strings.TrimRight(string(out), "\n"), "\n")
	want := []string{
		"statement,Trial balance",
		"definition,TB-STD v2",
		"ledger,ledger-a",
		"period,2026-03",
		"currency type,acct",
		"",
		"row,label,Closing,Prior year",
		"HDR,Assets,,",
		`CASH,"  Cash",1250.500000,n/a`,
		"EQ,Equity,-300.000000,0.000000",
		"",
		"as of sequence,ledger-a,7",
		"as of sequence,ledger-b,9",
		"result hash,abc123",
		"generated at,2026-04-01T06:00:00Z",
		"generated by,u1",
		"run,run-1",
	}
	if len(lines) != len(want) {
		t.Fatalf("got %d lines, want %d:\n%s", len(lines), len(want), out)
	}
	for i := range want {
		if lines[i] != want[i] {
			t.Errorf("line %d = %q, want %q", i, lines[i], want[i])
		}
	}
}

func TestRenderCSV_Deterministic(t *testing.T) {
	def, cells, st := renderFixture()
	a, err := RenderCSV(def, cells, st)
	if err != nil {
		t.Fatal(err)
	}
	b, err := RenderCSV(def, cells, st)
	if err != nil {
		t.Fatal(err)
	}
	if string(a) != string(b) {
		t.Fatal("two renders of the same input differ")
	}
}

// Labels are user text; a spreadsheet must not evaluate them as formulas.
func TestRenderCSV_NeutralizesFormulas(t *testing.T) {
	def, cells, st := renderFixture()
	def.Name = "=cmd|' /C calc'!A0"
	def.Rows[1].Label = "@SUM(A1)"
	def.Rows[1].Format.Indent = -3 // stored before indent was bounded; must not panic
	def.Columns[0].Label = "+1"
	out, err := RenderCSV(def, cells, st)
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{`statement,'=cmd|' /C calc'!A0`, "CASH,'@SUM(A1),", "row,label,'+1,"} {
		if !strings.Contains(string(out), want) {
			t.Errorf("missing %q in\n%s", want, out)
		}
	}
}
