func trimEmpty(rec []string) []string {
	var out []string
	for _, f := range rec {
		if f != "" {
			out = append(out, f)
		}
	}
	return out
}

func sheetXML(t *testing.T, out []byte) string {
	t.Helper()
	zr, err := zip.NewReader(bytes.NewReader(out), int64(len(out)))
	if err != nil {
		t.Fatal(err)
	}
	for _, f := range zr.File {
		if f.Name == "xl/worksheets/sheet1.xml" {
			rc, err := f.Open()
			if err != nil {
				t.Fatal(err)
			}
			defer rc.Close()
			body, err := io.ReadAll(rc)
			if err != nil {
				t.Fatal(err)
			}
			return string(body)
		}
	}
	t.Fatal("no sheet1.xml")
	return ""
}

var refRe = regexp.MustCompile(`^([A-Z]+)([0-9]+)$`)

// readSheet decodes sheet1.xml into rows of cell texts (row index = row
// number - 1, omitted cells skipped) and the set of numeric cell references.
func readSheet(t *testing.T, out []byte) ([][]string, map[string]bool) {
	t.Helper()
	var ws struct {
		Rows []struct {
			R     int `xml:"r,attr"`
			Cells []struct {
				R string `xml:"r,attr"`
				T string `xml:"t,attr"`
				V string `xml:"v"`
				S string `xml:"is>t"`
			} `xml:"c"`
		} `xml:"sheetData>row"`
	}
	if err := xml.Unmarshal([]byte(sheetXML(t, out)), &ws); err != nil {
		t.Fatal(err)
	}
	var grid [][]string
	numeric := map[string]bool{}
	for _, row := range ws.Rows {
		for len(grid) < row.R {
			grid = append(grid, nil)
		}
		for _, c := range row.Cells {
			m := refRe.FindStringSubmatch(c.R)
			if m == nil || m[2] != strconv.Itoa(row.R) {
				t.Fatalf("cell ref %q is not in row %d", c.R, row.R)
			}
			if c.T == "inlineStr" {
				grid[row.R-1] = append(grid[row.R-1], c.S)
			} else {
				grid[row.R-1] = append(grid[row.R-1], c.V)
				numeric[c.R] = true
			}
		}
	}
	return grid, numeric
}
