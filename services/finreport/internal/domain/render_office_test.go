// Definition text is user input; it must not become markup.
func TestRenderHTML_EscapesDefinitionText(t *testing.T) {
	def, cells, st := renderFixture()
	def.Name = `<script>alert("x")</script>`
	def.Rows[1].Label = `Cash & "bank" <b>`
	def.Columns[0].Label = `<img src=x onerror=alert(1)>`
	st.GeneratedBy = `</dd><script>`
	out, err := RenderHTML(def, cells, st)
	if err != nil {
		t.Fatal(err)
	}
	s := string(out)
	for _, bad := range []string{"<script>", "<b>", "<img"} {
		if strings.Contains(s, bad) {
			t.Errorf("%q was not escaped:\n%s", bad, s)
		}
	}
	if !strings.Contains(s, "Cash &amp; &#34;bank&#34; &lt;b&gt;") {
		t.Errorf("label not escaped as expected:\n%s", s)
	}
}

