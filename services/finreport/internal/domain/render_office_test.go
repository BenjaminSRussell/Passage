// The workbook must hold exactly what the CSV holds: same header block, grid
// and footer, cell for cell. CSV writes blank cells as empty fields; the sheet
// leaves them out.
func TestRenderXLSX_SameContentAsCSV(t *testing.T) {
	def, cells, st := renderFixture()
	csvOut, err := RenderCSV(def, cells, st)
	if err != nil {
		t.Fatal(err)
	}
	reader := csv.NewReader(bytes.NewReader(csvOut))
	reader.FieldsPerRecord = -1
	want, err := reader.ReadAll()
	if err != nil {
		t.Fatal(err)
	}
	xlsxOut, err := RenderXLSX(def, cells, st)
	if err != nil {
		t.Fatal(err)
	}
	got, numeric := readSheet(t, xlsxOut)
	// encoding/csv skips blank lines, so compare the non-empty rows in order.
	var gotRows [][]string
	for _, row := range got {
		if len(row) > 0 {
			gotRows = append(gotRows, row)
		}
	}
	if len(gotRows) != len(want) {
		t.Fatalf("sheet has %d rows, csv %d:\nsheet %q\ncsv %q", len(gotRows), len(want), gotRows, want)
	}
	for i := range want {
		if w, g := strings.Join(trimEmpty(want[i]), "|"), strings.Join(gotRows[i], "|"); w != g {
			t.Errorf("row %d: sheet %q, csv %q", i, g, w)
		}
	}
	// Amounts are numbers; the label column, "n/a" and the footer are text.
	for ref, want := range map[string]bool{"C9": true, "D9": false, "C10": true, "D10": true, "B9": false, "C13": false} {
		if numeric[ref] != want {
			t.Errorf("cell %s numeric = %v, want %v", ref, numeric[ref], want)
		}
	}
	// The blank rows after the header block and the grid are kept.
	if len(got[5]) != 0 || len(got[10]) != 0 {
		t.Errorf("expected blank rows 6 and 11: %q", got)
	}
}

// Labels are inline strings: escaped as XML, leading spaces kept, and a
// leading "=" stays text rather than becoming a formula.
func TestRenderXLSX_TextCellsAreEscapedInlineStrings(t *testing.T) {
	def, cells, st := renderFixture()
	def.Rows[2].Label = `=Equity <&> "x"`
	def.Rows[1].Format.Indent = -3 // stored before indent was bounded; must not panic
	out, err := RenderXLSX(def, cells, st)
	if err != nil {
		t.Fatal(err)
	}
	sheet := sheetXML(t, out)
	if !strings.Contains(sheet, `<c r="B10" t="inlineStr"><is><t xml:space="preserve">=Equity &lt;&amp;&gt; &#34;x&#34;</t></is></c>`) {
		t.Errorf("label not an escaped inline string:\n%s", sheet)
	}
	if strings.Contains(sheet, "<f>") {
		t.Errorf("the sheet must not contain formulas:\n%s", sheet)
	}
	if !strings.Contains(sheet, `<c r="B9" t="inlineStr"><is><t xml:space="preserve">Cash</t></is></c>`) {
		t.Errorf("negative indent should render unindented:\n%s", sheet)
	}
}

func TestRenderXLSX_WorkbookPartsAndDeterminism(t *testing.T) {
	def, cells, st := renderFixture()
	a, err := RenderXLSX(def, cells, st)
	if err != nil {
		t.Fatal(err)
	}
	b, err := RenderXLSX(def, cells, st)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(a, b) {
		t.Fatal("two renders of the same input differ")
	}
	zr, err := zip.NewReader(bytes.NewReader(a), int64(len(a)))
	if err != nil {
		t.Fatalf("not a zip: %v", err)
	}
	names := map[string]bool{}
	for _, f := range zr.File {
		names[f.Name] = true
		rc, err := f.Open()
		if err != nil {
			t.Fatal(err)
		}
		body, err := io.ReadAll(rc)
		_ = rc.Close()
		if err != nil {
			t.Fatal(err)
		}
		// Every part must be well-formed XML.
		dec := xml.NewDecoder(bytes.NewReader(body))
		for {
			if _, err := dec.Token(); err == io.EOF {
				break
			} else if err != nil {
				t.Fatalf("%s is not well-formed XML: %v", f.Name, err)
			}
		}
	}
	for _, name := range []string{"[Content_Types].xml", "_rels/.rels", "xl/workbook.xml", "xl/_rels/workbook.xml.rels", "xl/worksheets/sheet1.xml"} {
		if !names[name] {
			t.Errorf("missing part %s", name)
		}
	}
}

