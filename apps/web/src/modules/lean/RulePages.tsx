function capacity(r: Rule): string {
  return r.numberOfKanbans === null ? String(r.activeKanbans) : `${r.activeKanbans} of ${r.numberOfKanbans}`;
}

const listColumns: DataTableColumn<Rule>[] = [
  { key: "code", header: "Rule", mono: true },
  { key: "ruleType", header: "Type", render: (r) => (r.ruleType === "manufacturing" ? "Manufacturing" : "Withdrawal") },
  { key: "replenishment", header: "Replenishment", render: (r) => <Badge tone="neutral">{REPLENISHMENT_LABELS[r.replenishment]}</Badge> },
  { key: "fixedQty", header: "Quantity per card", align: "end" },
  { key: "activeKanbans", header: "Active cards", align: "end", render: capacity },
  { key: "leadTimeH", header: "Lead time (h)", align: "end" },
  { key: "itemId", header: "Item", mono: true, render: (r) => shortId(r.itemId) },
];

/** Kanban rules (FR-24.9), optionally for one flow. */
export function RulesPage() {
  const navigate = useNavigate();
  const [params] = useSearchParams();
  const flowId = params.get("flowId") ?? "";
  const state = useLoad((signal) => listRules(flowId, signal), `rules|${flowId}`);
  return (
    <div className={styles.stack}>
      <PageHeader
        title="Kanban rules"
        description={flowId ? "Rules that replenish through this production flow." : "How each item is replenished: fixed cards, scheduled by planning, or generated by events."}
        actions={
          <Link className={buttonClassName("primary")} to={flowId ? `/lean/rules/new?flowId=${flowId}` : "/lean/rules/new"}>
            New rule
          </Link>
        }
      />
      {state.error ? (
        <Alert tone="danger" title="Could not load kanban rules" live="alert" action={<Button size="sm" onClick={state.reload}>Try again</Button>}>
          {state.error.message} ({state.error.code})
        </Alert>
      ) : (
        <DataTable
          label="Kanban rules"
          columns={listColumns}
          rows={state.data ?? []}
          getRowKey={(r) => r.id}
          loading={state.loading}
          empty={{ title: "No kanban rules yet", description: "Create a rule to start replenishing an item with kanbans." }}
          onRowOpen={(r) => navigate(`/lean/rules/${r.id}`)}
        />
      )}
    </div>
  );
}

interface RuleValues {
  code: string;
  itemId: string;
  siteId: string;
  flowId: string;
  ruleType: RuleType;
  replenishment: Replenishment;
  fixedQty: string;
  numberOfKanbans: string;
  leadTimeH: string;
  eventSource: EventSource;
  exactQty: boolean;
  effectiveFrom: string;
}

type RuleErrors = Partial<Record<keyof RuleValues, string>>;

const CODE = /^[A-Z0-9][A-Z0-9_.-]{0,31}$/;

/** Checks that mirror the service (FR-24.9), and the request the form produces. */
export function validateRule(values: RuleValues): { errors: RuleErrors; input?: NewRule } {
  const errors: RuleErrors = {};
  if (!CODE.test(values.code)) errors.code = "Use 1 to 32 capital letters, digits, _, . or -, starting with a letter or digit.";
  if (!UUID.test(values.itemId.trim())) errors.itemId = "Enter the item id (a UUID).";
  if (!UUID.test(values.siteId.trim())) errors.siteId = "Enter the site id (a UUID).";
  if (!positiveQuantity(values.fixedQty)) errors.fixedQty = "Enter a positive quantity with at most 6 decimals.";
  if (values.replenishment === "fixed" && !/^[1-9]\d{0,3}$/.test(values.numberOfKanbans)) errors.numberOfKanbans = "Enter 1 to 1000 cards.";
  else if (values.replenishment === "fixed" && Number(values.numberOfKanbans) > 1000) errors.numberOfKanbans = "Enter 1 to 1000 cards.";
  if (!/^\d{1,4}$/.test(values.leadTimeH) || Number(values.leadTimeH) > 8760) errors.leadTimeH = "Enter 0 to 8760 hours.";
  if (!/^\d{4}-\d{2}-\d{2}$/.test(values.effectiveFrom)) errors.effectiveFrom = "Choose a date.";
  if (Object.keys(errors).length > 0) return { errors };
  return {
    errors,
    input: {
      code: values.code,
      itemId: values.itemId.trim(),
      siteId: values.siteId.trim(),
      flowId: values.flowId === "" ? null : values.flowId,
      ruleType: values.ruleType,
      replenishment: values.replenishment,
      fixedQty: values.fixedQty,
      numberOfKanbans: values.replenishment === "fixed" ? Number(values.numberOfKanbans) : null,
      leadTimeH: Number(values.leadTimeH),
      eventSource: values.replenishment === "event" ? values.eventSource : null,
      exactQty: values.replenishment === "event" && values.exactQty,
      effectiveFrom: values.effectiveFrom,
    },
  };
}

/** Create a kanban rule; for a fixed rule, the BR-24.7 helper suggests the number of cards. */
export function NewRulePage() {
  const navigate = useNavigate();
  const [params] = useSearchParams();
  const flows = useLoad((signal) => listFlows("", signal), "flows");
  const [values, setValues] = useState<RuleValues>({
    code: "",
    itemId: "",
    siteId: "",
    flowId: params.get("flowId") ?? "",
    ruleType: "manufacturing",
    replenishment: "fixed",
    fixedQty: "",
    numberOfKanbans: "",
    leadTimeH: "8",
    eventSource: "sales",
    exactQty: false,
    effectiveFrom: today(),
  });
  const [demand, setDemand] = useState({ dailyDemand: "", safetyPct: "10" });
  const [suggestion, setSuggestion] = useState<string | null>(null);
  const [errors, setErrors] = useState<RuleErrors>({});
  const [failure, setFailure] = useState<Problem | null>(null);
  const [busy, setBusy] = useState(false);
  const key = useRef(newKey());

  function update(patch: Partial<RuleValues>) {
    setValues({ ...values, ...patch });
    key.current = newKey();
  }

  async function suggest() {
    setSuggestion(null);
    if (!QUANTITY.test(demand.dailyDemand) || !QUANTITY.test(demand.safetyPct) || !positiveQuantity(values.fixedQty) || !/^\d+$/.test(values.leadTimeH)) {
      setSuggestion("Enter the daily demand, safety %, quantity per card and lead time first.");
      return;
    }
    try {
      // Lead time in days with 4 decimals, from whole hours, without floating point.
      const hours = BigInt(values.leadTimeH) * 10000n;
      const days = (hours / 24n).toString().padStart(5, "0");
      const leadTimeDays = `${days.slice(0, -4)}.${days.slice(-4)}`;
      const { numberOfKanbans } = await suggestFixedCount({ dailyDemand: demand.dailyDemand, leadTimeDays, safetyPct: demand.safetyPct, fixedQty: values.fixedQty });
      update({ numberOfKanbans: String(numberOfKanbans) });
      setSuggestion(`Suggested ${numberOfKanbans} cards. You can change it.`);
    } catch (error) {
      const problem = describeProblem(error);
      setSuggestion(`${problem.message} (${problem.code})`);
    }
  }

  async function submit(event: FormEvent) {
    event.preventDefault();
    const { errors: found, input } = validateRule(values);
    setErrors(found);
    setFailure(null);
    if (!input) return;
    setBusy(true);
    try {
      const rule = await createRule(input, key.current);
      navigate(`/lean/rules/${rule.id}`);
    } catch (error) {
      const problem = describeProblem(error);
      if (problem.code === "LEAN-0105") setErrors({ code: "A rule with this code already exists." });
      else setFailure(problem);
      if (problem.code === "idempotency_key_reuse") key.current = newKey();
    } finally {
      setBusy(false);
    }
  }

  return (
    <div className={styles.stack}>
      <PageHeader title="New kanban rule" description="Fixed rules keep a set number of cards in circulation; event rules create cards for each demand line." />
      <form className={styles.stack} onSubmit={submit} noValidate>
        <Card title="Rule">
          <div className={styles.form}>
            <FormField id="rule-code" label="Code" hint="Cards are numbered CODE-0001, CODE-0002, …" error={errors.code}>
              {(c) => <Input {...c} value={values.code} maxLength={32} onChange={(e) => update({ code: e.target.value.toUpperCase() })} invalid={Boolean(errors.code)} />}
            </FormField>
            <FormField id="rule-item" label="Item id" error={errors.itemId}>
              {(c) => <Input {...c} className={styles.mono} value={values.itemId} onChange={(e) => update({ itemId: e.target.value })} invalid={Boolean(errors.itemId)} />}
            </FormField>
            <FormField id="rule-site" label="Site id" error={errors.siteId}>
              {(c) => <Input {...c} className={styles.mono} value={values.siteId} onChange={(e) => update({ siteId: e.target.value })} invalid={Boolean(errors.siteId)} />}
            </FormField>
            <FormField id="rule-flow" label="Production flow" optional>
              {(c) => (
                <Select {...c} value={values.flowId} onChange={(e) => update({ flowId: e.target.value })}>
                  <option value="">No flow</option>
                  {(flows.data ?? []).map((f) => (
                    <option key={f.id} value={f.id}>
                      {f.name}
                    </option>
                  ))}
                </Select>
              )}
            </FormField>
            <FormField id="rule-type" label="Rule type">
              {(c) => (
                <Select {...c} value={values.ruleType} onChange={(e) => update({ ruleType: e.target.value as RuleType })}>
                  <option value="manufacturing">Manufacturing</option>
                  <option value="withdrawal">Withdrawal</option>
                </Select>
              )}
            </FormField>
            <FormField id="rule-replenishment" label="Replenishment">
              {(c) => (
                <Select {...c} value={values.replenishment} onChange={(e) => update({ replenishment: e.target.value as Replenishment })}>
                  <option value="fixed">Fixed</option>
                  <option value="event">Event</option>
                  <option value="scheduled">Scheduled</option>
                </Select>
              )}
            </FormField>
            <FormField id="rule-qty" label="Quantity per card" error={errors.fixedQty}>
              {(c) => <Input {...c} inputMode="decimal" value={values.fixedQty} onChange={(e) => update({ fixedQty: e.target.value })} invalid={Boolean(errors.fixedQty)} />}
            </FormField>
            <FormField id="rule-lead" label="Lead time (hours)" error={errors.leadTimeH}>
              {(c) => <Input {...c} inputMode="numeric" value={values.leadTimeH} onChange={(e) => update({ leadTimeH: e.target.value })} invalid={Boolean(errors.leadTimeH)} />}
            </FormField>
            <FormField id="rule-from" label="Effective from" error={errors.effectiveFrom}>
              {(c) => <Input {...c} type="date" value={values.effectiveFrom} onChange={(e) => update({ effectiveFrom: e.target.value })} invalid={Boolean(errors.effectiveFrom)} />}
            </FormField>
          </div>
        </Card>
        {values.replenishment === "fixed" ? (
          <Card title="Number of cards">
            <div className={styles.form}>
              <FormField id="rule-kanbans" label="Number of kanbans" error={errors.numberOfKanbans}>
                {(c) => <Input {...c} inputMode="numeric" value={values.numberOfKanbans} onChange={(e) => update({ numberOfKanbans: e.target.value })} invalid={Boolean(errors.numberOfKanbans)} />}
              </FormField>
              <FormField id="rule-demand" label="Daily demand" optional hint="For the suggestion only.">
                {(c) => <Input {...c} inputMode="decimal" value={demand.dailyDemand} onChange={(e) => setDemand({ ...demand, dailyDemand: e.target.value })} />}
              </FormField>
              <FormField id="rule-safety" label="Safety (%)" optional>
                {(c) => <Input {...c} inputMode="decimal" value={demand.safetyPct} onChange={(e) => setDemand({ ...demand, safetyPct: e.target.value })} />}
              </FormField>
              <div className={styles.formActions}>
                <Button size="sm" onClick={() => void suggest()}>
                  Suggest number of kanbans
                </Button>
                {suggestion ? (
                  <span className={styles.note} role="status">
                    {suggestion}
                  </span>
                ) : null}
              </div>
            </div>
          </Card>
        ) : null}
        {values.replenishment === "event" ? (
          <Card title="Event">
            <div className={styles.form}>
              <FormField id="rule-source" label="Event source">
                {(c) => (
                  <Select {...c} value={values.eventSource} onChange={(e) => update({ eventSource: e.target.value as EventSource })}>
                    {EVENT_SOURCES.map((s) => (
                      <option key={s} value={s}>
                        {s}
                      </option>
                    ))}
                  </Select>
                )}
              </FormField>
              <div className={styles.formActions}>
                <span className={styles.check}>
                  <Input type="checkbox" id="rule-exact" checked={values.exactQty} onChange={(e) => update({ exactQty: e.target.checked })} />
                  <label htmlFor="rule-exact">Exact quantity</label>
                </span>
                <span className={styles.note}>The last card holds the remainder instead of a full card.</span>
              </div>
            </div>
          </Card>
        ) : null}
        {failure ? (
          <Alert tone="danger" title="Could not create the rule" live="alert">
            {failure.message} ({failure.code})
          </Alert>
        ) : null}
        <div className={styles.formActions}>
          <Button type="submit" variant="primary" loading={busy}>
            Create rule
          </Button>
          <Link className={buttonClassName("ghost")} to="/lean/rules">
            Cancel
          </Link>
        </div>
      </form>
    </div>
  );
}

const cardColumns: DataTableColumn<Kanban>[] = [
  { key: "cardNumber", header: "Card", mono: true },
  { key: "qty", header: "Quantity", align: "end" },
  { key: "state", header: "State", render: (k) => <StatusPill status={STATE_LABELS[k.state]} /> },
  { key: "due", header: "Due", render: (k) => formatDateTime(k.due) },
  { key: "eventRefId", header: "Demand", render: (k) => (k.eventRefId ? `${k.eventRefType ?? ""} ${k.eventRefId}`.trim() : dash) },
];

interface RuleDetail {
  rule: Rule;
  cards: Kanban[];
}

/** One rule, its cards and kanban generation (FR-24.9, FR-24.11, BR-24.7, BR-24.8). */
export function RuleDetailPage() {
  const { id = "" } = useParams();
  const state = useLoad<RuleDetail>(async (signal) => {
    const [rule, board] = await Promise.all([getRule(id, signal), fetchBoard({ ruleId: id }, signal)]);
    return { rule, cards: board.columns.flatMap((c) => c.kanbans) };
  }, id);
  const [count, setCount] = useState("");
  const [demandQty, setDemandQty] = useState("");
  const [refType, setRefType] = useState("sales-line");
  const [refId, setRefId] = useState("");
  const [inputError, setInputError] = useState<string | null>(null);
  const [failure, setFailure] = useState<Problem | null>(null);
  const [notice, setNotice] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);
  const key = useRef(newKey());

  if (state.error) {
    return (
      <div className={styles.stack}>
        <PageHeader title="Kanban rule" />
        <Alert tone="danger" title="Could not load the rule" live="alert" action={<Button size="sm" onClick={state.reload}>Try again</Button>}>
          {state.error.message} ({state.error.code})
        </Alert>
      </div>
    );
  }
  if (!state.data) {
    return (
      <div className={styles.stack} aria-busy="true">
        <PageHeader title="Kanban rule" />
        <span className="visually-hidden">Loading the rule…</span>
        <Skeleton height="tile" />
      </div>
    );
  }
  const { rule, cards } = state.data;

  async function generate(event: FormEvent) {
    event.preventDefault();
    setFailure(null);
    setNotice(null);
    setInputError(null);
    const input: Parameters<typeof generateKanbans>[0] = { ruleId: rule.id };
    if (rule.replenishment === "fixed") {
      if (count !== "" && !/^[1-9]\d{0,3}$/.test(count)) {
        setInputError("Enter a whole number of cards, or leave empty to fill the rule.");
        return;
      }
      if (count !== "") input.count = Number(count);
    } else {
      if (!positiveQuantity(demandQty)) {
        setInputError("Enter the demand quantity.");
        return;
      }
      input.demandQty = demandQty;
      if (refId.trim() !== "") {
        input.eventRefType = refType.trim() || "manual";
        input.eventRefId = refId.trim();
      }
    }
    setBusy(true);
    try {
      const created = await generateKanbans(input, key.current);
      key.current = newKey();
      setNotice(`${created.length} ${created.length === 1 ? "card" : "cards"} created: ${created.map((k) => k.cardNumber).join(", ")}.`);
      setCount("");
      setDemandQty("");
      setRefId("");
      state.reload();
    } catch (error) {
      setFailure(describeProblem(error));
      key.current = newKey();
    } finally {
      setBusy(false);
    }
  }

  return (
    <div className={styles.stack}>
      <PageHeader
        title={rule.code}
        description={`${rule.ruleType === "manufacturing" ? "Manufacturing" : "Withdrawal"} rule, ${REPLENISHMENT_LABELS[rule.replenishment].toLowerCase()} replenishment`}
        actions={
          <Link className={buttonClassName("secondary")} to={`/lean/board?ruleId=${rule.id}`}>
            Open board
          </Link>
        }
      />
      <StatGroup label="Rule facts">
        <StatTile label="Quantity per card" value={rule.fixedQty} />
        <StatTile label="Active cards" value={capacity(rule)} />
        <StatTile label="Lead time (h)" value={rule.leadTimeH} />
      </StatGroup>
      <Card title="Generate kanbans">
        {rule.replenishment === "scheduled" ? (
          <p className={styles.note}>Scheduled rules get their kanbans from master planning.</p>
        ) : (
          <div className={styles.stack}>
            <form className={styles.toolbar} onSubmit={generate} noValidate>
              {rule.replenishment === "fixed" ? (
                <FormField id="gen-count" label="Cards to add" optional hint="Leave empty to fill the rule." error={inputError ?? undefined}>
                  {(c) => <Input {...c} inputMode="numeric" value={count} onChange={(e) => setCount(e.target.value)} invalid={Boolean(inputError)} />}
                </FormField>
              ) : (
                <>
                  <FormField id="gen-demand" label="Demand quantity" error={inputError ?? undefined}>
                    {(c) => <Input {...c} inputMode="decimal" value={demandQty} onChange={(e) => setDemandQty(e.target.value)} invalid={Boolean(inputError)} />}
                  </FormField>
                  <FormField id="gen-ref-type" label="Demand type" optional>
                    {(c) => <Input {...c} value={refType} maxLength={80} onChange={(e) => setRefType(e.target.value)} />}
                  </FormField>
                  <FormField id="gen-ref" label="Demand reference" optional hint="For example SO-1042/10.">
                    {(c) => <Input {...c} value={refId} maxLength={80} onChange={(e) => setRefId(e.target.value)} />}
                  </FormField>
                </>
              )}
              <Button type="submit" variant="primary" loading={busy}>
                Generate kanbans
              </Button>
            </form>
            {notice ? <Alert tone="success" title={notice} live="status" /> : null}
            {failure ? (
              <Alert tone="danger" title="Could not generate kanbans" live="alert">
                {failure.message} ({failure.code})
              </Alert>
            ) : null}
          </div>
        )}
      </Card>
      <DataTable
        label="Kanban cards"
        columns={cardColumns}
        rows={cards}
        getRowKey={(k) => k.id}
        empty={{ title: "No cards yet", description: "Generate kanbans to put cards in circulation." }}
      />
      <p className={styles.muted}>{`Item ${rule.itemId} · site ${rule.siteId} · effective from ${rule.effectiveFrom}${rule.effectiveTo ? ` to ${rule.effectiveTo}` : ""}`}</p>
    </div>
  );
}
