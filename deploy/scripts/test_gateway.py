class GeneratedApiRoutes(unittest.TestCase):
    """D31 (B-02a, #661): every /api/v1/<prefix> the web shell calls has exactly one route on depot-api, every route reaches a
    Service and port a dev chart renders, and the generated files are what gen_httproutes.py writes."""

    @classmethod
    def setUpClass(cls):
        cls.docs = render()

    def test_generator_check_passes(self):
        res = subprocess.run([sys.executable, str(DEPLOY / "scripts" / "gen_httproutes.py"), "--check"], capture_output=True, text=True)
        self.assertEqual(res.returncode, 0, res.stderr)

    def test_every_shell_prefix_has_exactly_one_route_to_an_existing_service_port(self):
        self.assertGreater(len(MODEL.shell), 70)  # the scan found the shell's clients (about 80 prefixes)
        self.assertEqual(gen.route_problems(self.docs, MODEL.shell, MODEL.services), [])

    def test_shell_scan_finds_literal_and_root_joined_prefixes(self):
        shell = MODEL.shell
        # Literal bases, a path joined to the bare /api/v1 root (assets, the generic case routes, migration-factory), and
        # nothing from tests or the demo backend (which mocks /api/v1/x and /api/v1/default in tests only).
        for prefix in ["inventory", "procurement", "payables", "production", "warehouse", "hr", "treasury", "leases", "cases",
                       "case-mailboxes", "migration", "cutover", "edi", "mcp"]:
            self.assertIn(prefix, shell)
        for prefix in ["x", "default", "ledgerx", "api", "activities", "work-orders"]:
            self.assertNotIn(prefix, shell)

    def test_a_missing_route_fails_the_check(self):
        docs = [d for d in self.docs if not (d["kind"] == "HTTPRoute" and d["metadata"]["name"] == "inventory")]
        self.assertEqual(gen.route_problems(docs, MODEL.shell, MODEL.services),
                         ["/api/v1/inventory: 0 routes (none), want exactly one"])

    def test_a_second_route_for_a_prefix_fails_the_check(self):
        dup = copy.deepcopy(named(self.docs, "HTTPRoute", "treasury"))
        dup["metadata"]["name"] = "treasury-again"
        problems = gen.route_problems(self.docs + [dup], MODEL.shell, MODEL.services)
        self.assertIn("/api/v1/treasury: 2 routes (treasury, treasury-again), want exactly one", problems)

    def test_a_route_to_a_missing_service_or_port_fails_the_check(self):
        docs = copy.deepcopy(self.docs)
        route = named(docs, "HTTPRoute", "pricing")
        route["spec"]["rules"][0]["backendRefs"][0]["name"] = "pricing"  # the Service the hand-written route named
        named(docs, "HTTPRoute", "hr")["spec"]["rules"][1]["backendRefs"][0]["port"] = 9090
        problems = gen.route_problems(docs, MODEL.shell, MODEL.services)
        self.assertIn("HTTPRoute pricing: Service hello-ledger/pricing is not rendered by any dev chart", problems)
        self.assertIn("HTTPRoute hr: Service hello-ledger/hr-depot-hr has http port 8080, not 9090", problems)

    def test_a_cross_namespace_backend_needs_its_reference_grant(self):
        docs = [d for d in self.docs if not (d["kind"] == "ReferenceGrant" and d["metadata"]["namespace"] == "batch")]
        problems = gen.route_problems(docs, MODEL.shell, MODEL.services)
