    def test_routes_rewrite_the_public_prefix_to_the_base_the_service_serves(self):
        """/api/v1/<prefix> and /v1/<prefix> both reach the service under the base its OpenAPI document uses: /v1/<prefix> by
        convention (pass-through on /v1), or the D22 exception's own base (/api/v1/<prefix>, /edi/v1, /print/v1, /mcp)."""
        for route in api_routes(self.docs):
            name = route["metadata"]["name"]
            model = ROUTE_MODEL[name]
            want = dict(model.matches())
            if model.elements:
                want |= {f"/v1/{model.prefix}/{e}": f"{model.upstream}/{e}" for e in model.elements}
            got = {}
            for rule in route["spec"]["rules"]:
                rewrite = rule.get("filters", [{}])[0].get("urlRewrite", {}).get("path", {}).get("replacePrefixMatch")
                for match in rule["matches"]:
                    self.assertEqual(match["path"]["type"], "PathPrefix", name)
                    got[match["path"]["value"]] = rewrite or match["path"]["value"]
            self.assertEqual(got, want, name)
            if model.upstream == f"/v1/{model.prefix}":
                self.assertRegex(model.upstream, DOWNSTREAM_ROUTE_RE)
            for rule in route["spec"]["rules"]:
                self.assertEqual(rule["backendRefs"][0]["name"], model.backend.name)

